-- LogScope product UX extension; PostgreSQL 15+.
-- Core research tables are defined in 01_research_core.sql.
-- Product-only tables describe the intended SaaS UI, not deployed services.
-- Never store API keys in plaintext, raw IP addresses or sensitive HTTP bodies.
BEGIN;
SET search_path TO logscope, public;

CREATE TABLE IF NOT EXISTS workspaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(70) NOT NULL UNIQUE,
  display_name VARCHAR(140) NOT NULL,
  owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  timezone VARCHAR(80) NOT NULL DEFAULT 'Europe/Istanbul',
  retention_days SMALLINT NOT NULL DEFAULT 30 CHECK(retention_days BETWEEN 1 AND 365),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS workspace_memberships (
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  workspace_role VARCHAR(16) NOT NULL CHECK(workspace_role IN ('owner','admin','analyst','reviewer')),
  joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(workspace_id, user_id)
);

CREATE TABLE IF NOT EXISTS user_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  inviter_id BIGINT NOT NULL REFERENCES users(id),
  invitee_email VARCHAR(254) NOT NULL,
  role VARCHAR(16) NOT NULL CHECK(role IN ('admin','analyst','reviewer')),
  token_hash CHAR(64) NOT NULL UNIQUE,
  status VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','expired','revoked')),
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS password_reset_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK(used_at IS NULL OR used_at >= created_at)
);

CREATE TABLE IF NOT EXISTS api_credentials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  label VARCHAR(100) NOT NULL,
  key_prefix VARCHAR(16) NOT NULL,
  key_hash CHAR(64) NOT NULL UNIQUE,
  scopes TEXT[] NOT NULL DEFAULT ARRAY['events:write']::text[],
  revoked_at TIMESTAMPTZ,
  last_used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS integrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  provider VARCHAR(24) NOT NULL CHECK(provider IN ('django','rest_api','locust','postgresql','jsonl','webhook')),
  name VARCHAR(120) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','configured','enabled','disabled','error')),
  safe_settings JSONB NOT NULL DEFAULT '{}'::jsonb,
  secret_reference TEXT,
  last_check_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(workspace_id, provider, name)
);

CREATE TABLE IF NOT EXISTS onboarding_progress (
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  step_code VARCHAR(20) NOT NULL CHECK(step_code IN ('workspace','source','privacy','first_analysis')),
  completed_at TIMESTAMPTZ,
  changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  PRIMARY KEY(workspace_id, step_code)
);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind VARCHAR(24) NOT NULL CHECK(kind IN ('alarm','ingestion','experiment','system','invitation')),
  severity VARCHAR(12) NOT NULL CHECK(severity IN ('info','warning','critical')),
  title VARCHAR(180) NOT NULL,
  message TEXT NOT NULL,
  related_alarm_id BIGINT REFERENCES alarms(id) ON DELETE SET NULL,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notification_preferences (
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  notify_critical BOOLEAN NOT NULL DEFAULT TRUE,
  notify_ingestion BOOLEAN NOT NULL DEFAULT TRUE,
  notify_system BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY(workspace_id, user_id)
);

CREATE TABLE IF NOT EXISTS report_exports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  requested_by BIGINT NOT NULL REFERENCES users(id),
  report_type VARCHAR(22) NOT NULL CHECK(report_type IN ('alarms_csv','traffic_csv','evaluation_csv','overview_pdf')),
  date_from TIMESTAMPTZ,
  date_to TIMESTAMPTZ,
  status VARCHAR(12) NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','processing','completed','failed')),
  artifact_ref TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  CHECK(date_from IS NULL OR date_to IS NULL OR date_from <= date_to)
);

CREATE TABLE IF NOT EXISTS audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action_code VARCHAR(70) NOT NULL,
  target_type VARCHAR(80) NOT NULL,
  target_ref VARCHAR(100),
  safe_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Future commercial module only. Payment processor integration is not implemented.
CREATE TABLE IF NOT EXISTS product_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  label VARCHAR(100) NOT NULL,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  monthly_price_minor BIGINT CHECK(monthly_price_minor IS NULL OR monthly_price_minor >= 0),
  currency CHAR(3),
  feature_limits JSONB NOT NULL DEFAULT '{}'::jsonb,
  CHECK((monthly_price_minor IS NULL AND currency IS NULL) OR (monthly_price_minor IS NOT NULL AND currency IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS workspace_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  plan_id BIGINT NOT NULL REFERENCES product_plans(id),
  status VARCHAR(14) NOT NULL CHECK(status IN ('trial','active','past_due','cancelled','demo')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  external_subscription_ref TEXT UNIQUE,
  CHECK(ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE IF NOT EXISTS invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id BIGINT NOT NULL REFERENCES workspace_subscriptions(id),
  external_invoice_ref TEXT UNIQUE,
  currency CHAR(3) NOT NULL,
  amount_minor BIGINT NOT NULL CHECK(amount_minor >= 0),
  invoice_status VARCHAR(12) NOT NULL CHECK(invoice_status IN ('draft','open','paid','void')),
  issued_at TIMESTAMPTZ NOT NULL,
  paid_at TIMESTAMPTZ,
  CHECK(paid_at IS NULL OR paid_at >= issued_at)
);

-- Multi-workspace links are nullable during backward-compatible migration.
ALTER TABLE scenario_runs ADD COLUMN IF NOT EXISTS workspace_id BIGINT REFERENCES workspaces(id);
ALTER TABLE ingestion_batches ADD COLUMN IF NOT EXISTS workspace_id BIGINT REFERENCES workspaces(id);
ALTER TABLE model_versions ADD COLUMN IF NOT EXISTS workspace_id BIGINT REFERENCES workspaces(id);
ALTER TABLE alarms ADD COLUMN IF NOT EXISTS workspace_id BIGINT REFERENCES workspaces(id);

CREATE INDEX IF NOT EXISTS ix_memberships_user ON workspace_memberships(user_id);
CREATE INDEX IF NOT EXISTS ix_integrations_workspace_status ON integrations(workspace_id,status);
CREATE INDEX IF NOT EXISTS ix_notifications_user_unread ON notifications(user_id,created_at DESC) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_audit_workspace_time ON audit_events(workspace_id,occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_reports_workspace_time ON report_exports(workspace_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_events_workspace_time ON http_events(occurred_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ux_workspace_active_subscription
  ON workspace_subscriptions(workspace_id) WHERE status IN ('trial','active','past_due','demo');
COMMIT;
