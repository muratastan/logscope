-- LogScope | PostgreSQL 15+ logical schema, version 1.0
-- Course design deliverable: no production data, no real experiments or users.
-- PII is excluded by application validation; never persist raw IP, cookies, token,
-- request body, passwords, or sensitive query parameter values in these tables.
BEGIN;
CREATE SCHEMA IF NOT EXISTS logscope;
SET search_path TO logscope, public;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role VARCHAR(16) NOT NULL CHECK (role IN ('analyst', 'admin')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (position('@' in email) > 1)
);

CREATE TABLE IF NOT EXISTS scenario_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_code VARCHAR(40) NOT NULL CHECK (scenario_code IN (
    'normal_steady','normal_hourly_rise','normal_campaign','normal_route_mix',
    'anomaly_5xx','anomaly_latency','anomaly_login_fail','anomaly_rare_route'
  )),
  traffic_class VARCHAR(12) NOT NULL CHECK (traffic_class IN ('normal','anomaly')),
  random_seed INTEGER NOT NULL,
  started_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  config JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE IF NOT EXISTS ingestion_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_name VARCHAR(160) NOT NULL,
  schema_version VARCHAR(16) NOT NULL DEFAULT '1.0',
  state VARCHAR(16) NOT NULL DEFAULT 'received'
    CHECK (state IN ('received','processing','completed','failed')),
  accepted_rows INTEGER NOT NULL DEFAULT 0 CHECK (accepted_rows >= 0),
  rejected_rows INTEGER NOT NULL DEFAULT 0 CHECK (rejected_rows >= 0),
  duplicate_rows INTEGER NOT NULL DEFAULT 0 CHECK (duplicate_rows >= 0),
  error_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS synthetic_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_ref UUID NOT NULL UNIQUE,
  scenario_run_id BIGINT NOT NULL REFERENCES scenario_runs(id),
  first_seen_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL,
  CHECK (last_seen_at >= first_seen_at)
);

CREATE TABLE IF NOT EXISTS http_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_uid UUID NOT NULL UNIQUE,
  ingestion_batch_id BIGINT NOT NULL REFERENCES ingestion_batches(id),
  scenario_run_id BIGINT NOT NULL REFERENCES scenario_runs(id),
  synthetic_session_id BIGINT REFERENCES synthetic_sessions(id),
  occurred_at TIMESTAMPTZ NOT NULL,
  http_method VARCHAR(8) NOT NULL CHECK (http_method IN ('GET','POST','PUT','PATCH','DELETE','HEAD','OPTIONS')),
  route_template VARCHAR(160) NOT NULL CHECK (route_template LIKE '/%' AND route_template NOT LIKE '%?%'),
  status_code SMALLINT NOT NULL CHECK (status_code BETWEEN 100 AND 599),
  duration_ms NUMERIC(12,3) NOT NULL CHECK (duration_ms >= 0),
  schema_version VARCHAR(16) NOT NULL DEFAULT '1.0',
  ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Aggregated labels exist ONLY for evaluation; never put labels, run identifiers or
-- random seeds in the feature vector passed to ML estimators.
CREATE TABLE IF NOT EXISTS traffic_windows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_run_id BIGINT NOT NULL REFERENCES scenario_runs(id),
  window_start TIMESTAMPTZ NOT NULL,
  window_end TIMESTAMPTZ NOT NULL,
  scope VARCHAR(8) NOT NULL CHECK (scope IN ('global','route')),
  route_template VARCHAR(160),
  request_count INTEGER NOT NULL CHECK (request_count >= 0),
  count_4xx INTEGER NOT NULL DEFAULT 0 CHECK (count_4xx >= 0),
  count_5xx INTEGER NOT NULL DEFAULT 0 CHECK (count_5xx >= 0),
  p50_duration_ms NUMERIC(12,3),
  p95_duration_ms NUMERIC(12,3),
  distinct_session_count INTEGER NOT NULL DEFAULT 0 CHECK (distinct_session_count >= 0),
  route_diversity INTEGER NOT NULL DEFAULT 0 CHECK (route_diversity >= 0),
  avg_request_interval_ms NUMERIC(12,3),
  features JSONB NOT NULL DEFAULT '{}'::jsonb,
  ground_truth_label VARCHAR(12) NOT NULL CHECK (ground_truth_label IN ('normal','anomaly','ambiguous')),
  dataset_split VARCHAR(12) NOT NULL CHECK (dataset_split IN ('train','validation','test','excluded')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (window_end = window_start + INTERVAL '1 minute'),
  CHECK (count_4xx + count_5xx <= request_count),
  CHECK ((scope = 'global' AND route_template IS NULL) OR (scope = 'route' AND route_template IS NOT NULL))
);
-- COALESCE handles unique global windows whose route_template is NULL.
CREATE UNIQUE INDEX IF NOT EXISTS ux_window_scope_start
  ON traffic_windows (scenario_run_id, window_start, scope, (COALESCE(route_template,'__GLOBAL__')));

CREATE TABLE IF NOT EXISTS model_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  component VARCHAR(12) NOT NULL CHECK (component IN ('B0','M1','M2','M3','M4')),
  algorithm VARCHAR(48) NOT NULL,
  version_tag VARCHAR(48) NOT NULL,
  config JSONB NOT NULL DEFAULT '{}'::jsonb,
  artifact_ref TEXT,
  training_end_at TIMESTAMPTZ,
  validation_end_at TIMESTAMPTZ,
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (component, algorithm, version_tag),
  CHECK (training_end_at IS NULL OR validation_end_at IS NULL OR training_end_at <= validation_end_at)
);

CREATE TABLE IF NOT EXISTS learned_patterns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_version_id BIGINT NOT NULL REFERENCES model_versions(id),
  route_sequence TEXT[] NOT NULL,
  support_count INTEGER NOT NULL CHECK (support_count >= 1),
  relative_support DOUBLE PRECISION NOT NULL CHECK (relative_support BETWEEN 0 AND 1),
  UNIQUE (model_version_id, route_sequence),
  CHECK (cardinality(route_sequence) IN (2,3))
);

CREATE TABLE IF NOT EXISTS model_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  window_id BIGINT NOT NULL REFERENCES traffic_windows(id),
  model_version_id BIGINT NOT NULL REFERENCES model_versions(id),
  signal VARCHAR(12) NOT NULL CHECK (signal IN ('B0','M1','M2','M3','M4')),
  raw_score DOUBLE PRECISION,
  normalized_score DOUBLE PRECISION CHECK (normalized_score BETWEEN 0 AND 1),
  available BOOLEAN NOT NULL DEFAULT TRUE,
  unavailable_reason TEXT,
  scored_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (window_id, model_version_id, signal),
  CHECK (available = TRUE OR unavailable_reason IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS alarms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  window_id BIGINT NOT NULL REFERENCES traffic_windows(id),
  model_version_id BIGINT NOT NULL REFERENCES model_versions(id),
  condition_code VARCHAR(8) NOT NULL CHECK (condition_code IN ('B0','B1','B1+D','B1+S','B2')),
  combined_score DOUBLE PRECISION NOT NULL,
  threshold_score DOUBLE PRECISION NOT NULL,
  reason_summary TEXT NOT NULL,
  review_state VARCHAR(16) NOT NULL DEFAULT 'new'
    CHECK (review_state IN ('new','reviewing','confirmed','dismissed')),
  raised_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (window_id, model_version_id, condition_code)
);

CREATE TABLE IF NOT EXISTS alarm_signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alarm_id BIGINT NOT NULL REFERENCES alarms(id) ON DELETE CASCADE,
  model_version_id BIGINT REFERENCES model_versions(id),
  signal VARCHAR(8) NOT NULL CHECK (signal IN ('M1','M2','M3','M4')),
  normalized_score DOUBLE PRECISION CHECK (normalized_score BETWEEN 0 AND 1),
  contribution DOUBLE PRECISION,
  evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
  UNIQUE (alarm_id, signal)
);

CREATE TABLE IF NOT EXISTS alarm_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alarm_id BIGINT NOT NULL REFERENCES alarms(id),
  reviewer_user_id BIGINT NOT NULL REFERENCES users(id),
  decision VARCHAR(16) NOT NULL CHECK (decision IN ('reviewing','confirmed','dismissed')),
  note TEXT,
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS evaluation_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_version_id BIGINT NOT NULL REFERENCES model_versions(id),
  condition_code VARCHAR(8) NOT NULL CHECK (condition_code IN ('B0','B1','B1+D','B1+S','B2')),
  scenario_seed INTEGER NOT NULL,
  dataset_split VARCHAR(12) NOT NULL CHECK (dataset_split IN ('validation','test')),
  positive_precision DOUBLE PRECISION CHECK (positive_precision BETWEEN 0 AND 1),
  positive_recall DOUBLE PRECISION CHECK (positive_recall BETWEEN 0 AND 1),
  positive_f1 DOUBLE PRECISION CHECK (positive_f1 BETWEEN 0 AND 1),
  normal_fpr DOUBLE PRECISION CHECK (normal_fpr BETWEEN 0 AND 1),
  pr_auc DOUBLE PRECISION CHECK (pr_auc BETWEEN 0 AND 1),
  alarm_count INTEGER CHECK (alarm_count >= 0),
  p95_api_ms DOUBLE PRECISION CHECK (p95_api_ms >= 0),
  cpu_cost_ms DOUBLE PRECISION CHECK (cpu_cost_ms >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (model_version_id,condition_code,scenario_seed,dataset_split)
);

CREATE INDEX IF NOT EXISTS ix_events_time_route ON http_events (occurred_at DESC,route_template);
CREATE INDEX IF NOT EXISTS ix_events_session_time ON http_events (synthetic_session_id,occurred_at);
CREATE INDEX IF NOT EXISTS ix_events_run_time ON http_events (scenario_run_id,occurred_at);
CREATE INDEX IF NOT EXISTS ix_windows_split_time ON traffic_windows (dataset_split,window_start);
CREATE INDEX IF NOT EXISTS ix_windows_route_time ON traffic_windows (route_template,window_start);
CREATE INDEX IF NOT EXISTS ix_scores_window ON model_scores (window_id,signal);
CREATE INDEX IF NOT EXISTS ix_alarms_state_time ON alarms (review_state,raised_at DESC);
CREATE INDEX IF NOT EXISTS ix_reviews_alarm_time ON alarm_reviews (alarm_id,reviewed_at DESC);
CREATE INDEX IF NOT EXISTS ix_patterns_model ON learned_patterns (model_version_id);

CREATE OR REPLACE VIEW v_alarm_overview AS
SELECT a.id, a.condition_code, a.combined_score, a.threshold_score, a.reason_summary,
       a.review_state, a.raised_at, w.window_start, w.scope, w.route_template,
       mv.version_tag AS model_version
  FROM alarms AS a
  JOIN traffic_windows AS w ON w.id = a.window_id
  JOIN model_versions AS mv ON mv.id = a.model_version_id;
COMMIT;
